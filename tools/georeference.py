"""Привязка карты Гродненской губернии 1913 года к реальным координатам.

Карта старая, поэтому точку «Августов» нельзя поставить на глаз: нужно знать,
куда на этом листе попадают широта и долгота. Решение:

1. Берём 10 опорных городов, у которых есть значок на самой карте.
   Для каждого записываем пиксель значка и его широту и долготу.
2. Ищем аффинное преобразование (долгота, широта) -> (x, y) пикселя
   методом наименьших квадратов: подбираем 6 коэффициентов так,
   чтобы сумма квадратов ошибок по всем опорным городам была минимальной.
3. По найденной формуле считаем положение нужных мест (в том числе тех,
   которых на карте нет) и переводим в проценты для js/data.js.
4. Проверка: считаем, где должна пройти параллель 54° и меридиан «−7°»
   (от Пулкова), и сравниваем с градусной сеткой, напечатанной на карте.

Запуск: python tools/georeference.py  (нужен только Python 3, без библиотек)
"""

import sys

sys.stdout.reconfigure(encoding='utf-8')  # чтобы консоль Windows печатала «−» и кириллицу

MAP_W, MAP_H = 1700, 1820  # размер файла img/map-1913.jpg в пикселях

# опорные города: (x, y) значка на карте -> (широта, долгота)
CONTROL = {
    'Гродно': ((812, 398), (53.6779, 23.8297)),
    'Белосток': ((542, 708), (53.1325, 23.1688)),
    'Супрасль': ((609, 670), (53.2104, 23.3368)),
    'Крынки': ((778, 650), (53.2667, 23.7667)),
    'Брест': ((685, 1372), (52.0930, 23.7000)),
    'Волковыск': ((1030, 737), (53.1561, 24.4513)),
    'Слоним': ((1349, 784), (53.0869, 25.3163)),
    'Зельва': ((1156, 747), (53.1500, 24.8167)),
    'Друскеники': ((877, 187), (54.0156, 23.9714)),
    'Домброво': ((637, 395), (53.6528, 23.3472)),
}

# места, которые нужно поставить на карту
PLACES = {
    'Августов': (53.8436, 22.9799),
    'Красносток (Ружаносток)': (53.6347, 23.4044),
    'Скидель': (53.5833, 24.2500),
    'Лида': (53.8885, 25.2846),
}

PULKOVO = 30.3261  # меридианы на карте подписаны от Пулкова: «−7°» = 23,33° в. д.


def solve3(rows, values):
    """Наименьшие квадраты для y = a*lon + b*lat + c: решаем нормальные уравнения 3x3 методом Гаусса."""
    m = [[sum(r[i] * r[j] for r in rows) for j in range(3)] for i in range(3)]
    v = [sum(r[i] * t for r, t in zip(rows, values)) for i in range(3)]
    for i in range(3):
        pivot = max(range(i, 3), key=lambda k: abs(m[k][i]))
        m[i], m[pivot] = m[pivot], m[i]
        v[i], v[pivot] = v[pivot], v[i]
        for k in range(3):
            if k != i:
                f = m[k][i] / m[i][i]
                m[k] = [a - f * b for a, b in zip(m[k], m[i])]
                v[k] -= f * v[i]
    return [v[i] / m[i][i] for i in range(3)]


rows = [[lon, lat, 1] for (_, (lat, lon)) in CONTROL.values()]
cx = solve3(rows, [px for ((px, _), _) in CONTROL.values()])
cy = solve3(rows, [py for ((_, py), _) in CONTROL.values()])


def to_pixel(lat, lon):
    """Широта и долгота -> пиксель на карте 1913 года."""
    return cx[0] * lon + cx[1] * lat + cx[2], cy[0] * lon + cy[1] * lat + cy[2]


print('Ошибка привязки по опорным городам (пиксели из 1700):')
for name, ((x, y), (lat, lon)) in CONTROL.items():
    px, py = to_pixel(lat, lon)
    print(f'  {name:12} dx = {px - x:6.1f}   dy = {py - y:6.1f}')

print('\nКоординаты для js/data.js (в % от ширины и высоты карты):')
for name, (lat, lon) in PLACES.items():
    px, py = to_pixel(lat, lon)
    print(f'  {name:26} x: {px / MAP_W * 100:.1f}, y: {py / MAP_H * 100:.1f}')

print('\nПроверка по напечатанной сетке: сравните с линиями на самой карте')
for lon in (22.5, 24.0):
    x, y = to_pixel(54, lon)
    print(f'  параллель 54° при долготе {lon}: ({x:.0f}, {y:.0f})')
for lat in (53.0, 54.0):
    x, y = to_pixel(lat, PULKOVO - 7)
    print(f'  меридиан «−7°» при широте {lat}: ({x:.0f}, {y:.0f})')
